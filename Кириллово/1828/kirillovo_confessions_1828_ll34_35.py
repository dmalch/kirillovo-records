from verso.ru.dsl import (CONFESSION_LIST, CensusRole, Month, RecordDefaults, census_records,
                          household, member, page, person)
from verso.ru.dsl.marital_status import WIDOW
from verso.ru.dsl.statuses import ECON_PEASANT_FEMALE, ECON_PEASANT_MALE, SOLDIER_WIFE

# Исповедная роспись 1828 года, с. Кириллово (Успенское), Казанская церковь.
# Архив: ГАРО, ф. 627 оп. 298 д. 61.
#
# ЭТО НЕ ТА РОСПИСЬ, ГДЕ МАЛЬЧИКОВЫ. Дело содержит росписи ТРЁХ священников
# (ведомости № 20, 22, 23 по описи): нумерация дворов у каждой начинается
# заново, а нумерация страниц сквозная через всё дело. Здесь выписаны дворы
# 94–96 первой ведомости, страницы 34–35. Дворы 94–96 с Мальчиковыми — другая
# ведомость, страницы 80–81, см. `kirillovo_confessions_1828.py`.
#
# Тем не менее двор 95 отсюда связан с линией Мальчиковых напрямую: это
# КАЛЯГИНЫ, и внук главы двора, Александр Трофимов Калягин 16 лет, в 1843 году
# (МК брак № 28) женится вторым браком на «Елене Нестеровой МАЛЬЧИКОВОЙ» —
# а Елена Нестерова, 14 лет, стоит в дворе 94 страницы 80 той, другой
# ведомости. Двор 96 отсюда — ТРУШИНЫ («Никифор Максимов Трушин», МК 1856).
#
# СОСТОЯНИЕ ЧТЕНИЯ. Страницы 34–35 сняты как фотографии экрана с открытым PDF:
# сильный муар и потеря разрешения (см. `census-scans`, § «When the scans are
# photographs of a screen»). Дальше по делу, со страницы ~60, идут нормальные
# плоские сканы — качество этих трёх дворов заметно хуже остального дела.
# Файл помечен reviewed=False.
#
# Ссылки на метрики вынесены в обычные # -комментарии: в отличие от comment=
# они не попадают ни в CSV, ни в профиль — это заметки для читателя кода.
#
# Сословный заголовок раздела на этих страницах отсутствует; ниже, перед главой
# двора 98, стоит явное «Крестьянинъ». Сословие взято по умолчанию
# «экономические крестьяне» — как в РС 1811 и РС 1834 по этому селу.
census = census_records(
    "ГАРО", "627", "298", "61", "Кириллово", 1828,
    # --- л. 34 -------------------------------------------------------------
    # Двор 94. Номер «94» — единственная цифра в графе «Домовъ или дворовъ» на
    # всём листе; он стоит против строки «Вдова …», а строка «Иванъ» (конец
    # двора 93) проходит выше неё. Двор занимает нижние ~45 % листа и, судя по
    # отсутствию номера «95» ниже, доходит до конца листа.
    # Муж вдовы, Матвей, умер до 1828 и в росписи не значится; отчества сыновей
    # названы в самом подлиннике («Матвеевы»), а не выведены из имени матери.
    # NB: отчество вдовы «Матвеева» совпадает с отчеством её сыновей — либо её
    # отца тоже звали Матвеем, либо писец подставил имя мужа; по скану не
    # различить.
    *page("34",
    household("94",
              member(1, person("Матрона", "Матвеева"), CensusRole.HEAD, age=81,
                     marital_status=WIDOW),
              member(2, person("Киріллъ", "Матвеевъ"), CensusRole.SON, age=50),
              member(3, person("Логинъ", "Матвеевъ"), CensusRole.SON, age=40),
              member(4, person("Параскева", "Антонова"), CensusRole.WIFE, ref_member=2, age=41),
              member(5, person("Савелій"), CensusRole.SON, ref_member=2, age=24),
              member(6, person("Антонъ"), CensusRole.SON, ref_member=2, age=21),
              member(7, person("Акилина"), CensusRole.DAUGHTER, ref_member=2, age=17),
              member(8, person("Гавріилъ"), CensusRole.SON, ref_member=2, age=14),
              member(9, person("Евдокимъ"), CensusRole.SON, ref_member=2, age=10),
              member(10, person("Настасья", "Андреева"), CensusRole.WIFE, ref_member=5, age=24),
              member(11, person("Иванъ"), CensusRole.SON, ref_member=5, age=2),
              member(12, person("Параскева", "Антонова"), CensusRole.WIFE, ref_member=3, age=39),
              member(13, person("Настасья"), CensusRole.DAUGHTER, ref_member=3, age=5),
              member(14, person("Спиридонъ", "Матвеевъ"), None, age=68),
              ),
            ),
    # --- л. 34об -----------------------------------------------------------
    # Двор 95 — Филат Никифоров (Калягины). Порядок строк в подлиннике: глава,
    # жена, «Дѣти ихъ» (Козма, Кирил, Акилина, Иван), жена Козмы с их детьми,
    # жена Кирила, затем солдатка с сыном.
    # Солдатка с сыном — это семья ещё одного, старшего сына Филата: Трофим
    # Филатов (род. 1789, МК рожд. № 30; отец Стефаниды в МК 1818 № 176) взят
    # в рекруты после 1818, отчего его жена в росписи «салдатка», а сам он не
    # значится. Их сын Александр Трофимов Калягин прослеживается дальше по МК:
    # отец в 1837 № 31, жених вторым браком в 1843 № 28 (на Елене Нестеровой
    # Мальчиковой), отец в 1850 № 74 и 1853 № 73.
    *page("34об",
    household("95",
              # отец детей по МК Кириллово 1789 № 30, 1801 № 31, 1807 № 12, 1808 № 25, 1811 № 30, 1818 № 121
              member(1, person("Филатъ", "Никифоровъ"), CensusRole.HEAD, age=69),
              member(2, person("Екатерина", "Никифорова"), CensusRole.WIFE, age=47),
              member(3, person("Казма"), CensusRole.SON, age=27),
              # род. 1808 (МК Кириллово, рожд. № 25) — возраст сходится точно
              member(4, person("Кирілъ"), CensusRole.SON, age=20),
              # род. 1811 (МК Кириллово, рожд. № 30) — в росписи на год меньше
              member(5, person("Акилина"), CensusRole.DAUGHTER, age=16),
              member(6, person("Иванъ"), CensusRole.SON, age=14),
              member(7, person("Пелагея", "Панфилова"), CensusRole.WIFE, ref_member=3, age=28),
              # род. 1817 (МК Кириллово, рожд. № 188, отец «Казма Филатовъ») — независимое подтверждение и имени отца, и состава семьи.
              member(8, person("Анна"), CensusRole.DAUGHTER, ref_member=3, age=11),
              member(9, person("Марья"), CensusRole.DAUGHTER, ref_member=3, age=5),
              member(10, person("Матрена", "Васильева"), CensusRole.WIFE, ref_member=4, age=21),
              # Жена Трофима и их сын. Отношение к главе двора роспись не
              # называет («Салдатка ево …»), поэтому роль не проставлена;
              # отцовство Трофима — вывод из отчества сына, не из этой строки.
              member(11, person("Стефанида", "Терентьева", status=SOLDIER_WIFE), None, age=43),
              member(12, person("Александръ", "Трафимовъ"), CensusRole.SON, ref_member=11, age=16),
              ),
    # Двор 96 — Никифор Максимов с братьями (Трушины). Номер «96» стоит ровно
    # на высоте строки «Никифоръ Максимовъ». Двор переходит на л. 35.
    household("96",
              # женился в 1807 (МК Кириллово, брак № 20) — род. ок. 1788, возраст сходится. Фамилия по МК 1856: «Никифор Максимов Трушин»
              member(1, person("Никифоръ", "Максимовъ"), CensusRole.HEAD, age=39),
              # в МК Кириллово 1807, брак № 20 — «Евдокея Аверьянова».
              member(2, person("Евдокея", "Аверьянова"), CensusRole.WIFE, age=43),
              member(3, person("Семенъ"), CensusRole.SON, age=17),
              member(4, person("Юда"), CensusRole.SON, age=12),
              member(5, person("Марья"), CensusRole.DAUGHTER, age=8),
              member(6, person("Николай"), CensusRole.SON, age=6),
              member(7, person("Герасимъ", "Максимовъ"), CensusRole.BROTHER, age=31),
              # браки 1817 № 3 и 1819 № 44 (второй) — род. ок. 1798
              member(8, person("Прокопій", "Максимовъ"), CensusRole.BROTHER, age=29),
              # отец Василия в 1823 (МК рожд. № 27) — род. ок. 1800
              member(9, person("Кандратій", "Максимовъ"), CensusRole.BROTHER, age=28),
              member(10, person("Ксенія", "Андреева"), CensusRole.WIFE, ref_member=7, age=29),
              member(11, person("Агафья"), CensusRole.DAUGHTER, ref_member=7, age=5),
              member(12, person("Анна"), CensusRole.DAUGHTER, ref_member=7, age=2),
              # «Прокопьева жена Февронія Петрова»; сходится с МК Кириллово 1819, брак № 44 (второй брак Прокопия)
              member(13, person("Февронія", "Петрова"), CensusRole.WIFE, ref_member=8, age=28),
              # Двор 96 переходит на л. 35: строки ниже написаны там, у самого
              # верха листа, до начала двора 97. Отдельного номера у них нет.
              member(14, person("Марфа"), CensusRole.DAUGHTER, ref_member=8, age=6),
              member(15, person("Татіяна"), CensusRole.DAUGHTER, ref_member=8, age=3),
              member(16, person("Параскева", "Міхайлова"), CensusRole.WIFE, ref_member=9, age=25),
              # МК Кириллово 1823, рожд. № 27 крещён Василий, отец «Кондратий Максимов»
              member(17, person("Василій"), CensusRole.SON, ref_member=9, age=6),
              member(18, person("Ефимья"), CensusRole.DAUGHTER, ref_member=9, age=3),
              ),
            ),
    # --- л. 35: соседние дворы, НЕ расшифрованы ------------------------------
    # После двора 96 на том же листе идут дворы 97, 98 и 99. К семьям дворов
    # 94–96 они, по прочитанному, отношения не имеют, и разобраны слишком
    # неуверенно, чтобы вносить их в DSL. Записываю опознавательные строки,
    # чтобы следующий проход не начинал поиск заново:
    #   двор 97 — «Андрей Тимофѣевъ» 58, «Жена ево Василиса(?) Ѳедорова» 60,
    #             далее «Дѣти ихъ …» 26 М, 23 М, 28 Ж и ещё внук(?)/племянник;
    #   двор 98 — «Крестьянинъ Иванъ Васильевъ» 31, «Жена его Прасковья
    #             Аѳанасьева» 29, трое детей, затем второе семейство в том же
    #             дворе: Иванъ Аѳанасьевъ 55 с женой Аксиньей 33;
    #   двор 99 — начинается у самого нижнего края л. 35 и продолжается на
    #             следующем листе, которого в выгрузке нет.
    # Номера листов: «34» читается (первая цифра уверенно), в правом верхнем
    # углу л. 35 помета размыта до нечитаемого пятна — «35» взято по счёту от
    # л. 34, а не прочитано.
    record_month=Month.MARCH,
    # Вторая ведомость того же дела со своей нумерацией дворов — суффикс
    # разводит её вывод (CSV, имена документов и профилей) с мальчиковской.
    archive_suffix="стр-34-35",
    suffix_in_res_names=True,
    defaults=RecordDefaults(
        status_male=ECON_PEASANT_MALE,
        status_female=ECON_PEASANT_FEMALE,
    ),
    **CONFESSION_LIST,
)
