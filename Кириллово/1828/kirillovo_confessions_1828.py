#
# Все три двора — прямое продолжение РС 1811 (ГАТО 12-1-439), где Мальчиковы
# занимают дворы 439, 440 и 468:
#
#   двор 94 = линия Дмитрея Давыдова (двор 439 РС 1811). Сам он в 1811 записан
#     39 лет — ровно 56 в 1828; сыновья Нестеръ 13 и Василей 10 дают 30 и 27
#     против 32 и 26 в росписи.
